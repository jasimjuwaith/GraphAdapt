"""
Graph-ADAPT Data Schemas & Pydantic Contracts
Defines all interface models for GraphRAG payloads, Agent outputs, and LangGraph states.
"""

from typing import List, Dict, Any, Optional, Literal
from typing_extensions import TypedDict
from pydantic import BaseModel, Field


# ============================================================================
# 1. Causal Sub-Graph GraphRAG Schemas
# ============================================================================

class NodeEntity(BaseModel):
    """Represents a single graph node entity extracted from Sysmon/OCSF logs."""
    node_id: str = Field(description="Unique handle formatted as host_id:entity_type:identifier")
    label: Literal["Process", "File", "UserToken", "IPAddress"] = Field(description="Graph node label category")
    attributes: Dict[str, Any] = Field(
        description="Attributes including image_path, command_line, user_sid, hash, integrity_level, etc."
    )


class EdgeRelationship(BaseModel):
    """Represents a causal directed edge between two entity nodes."""
    source_id: str = Field(description="Source node identifier")
    target_id: str = Field(description="Target node identifier")
    relationship: Literal["SPAWNED", "WRITTEN_TO", "AUTHENTICATED_AS", "CONNECTED_TO"] = Field(
        description="Directional causal relationship label"
    )


class SubGraphPayload(BaseModel):
    """3-Hop depth-bounded causal sub-graph payload extracted via Cypher GraphRAG."""
    root_pid: int = Field(description="Target process ID that triggered the alert misfire")
    target_host: str = Field(description="Hostname where event occurred")
    trigger_rule_id: str = Field(description="Sigma Rule ID flagged as degraded")
    nodes: List[NodeEntity] = Field(description="List of graph nodes within 3-hop traversal depth")
    edges: List[EdgeRelationship] = Field(description="List of causal directed relationships")


# ============================================================================
# 2. Agent Output Schemas
# ============================================================================

class ContextCorrelatorOutput(BaseModel):
    """Structured analysis output produced by the Context Correlator Agent."""
    execution_lineage: List[str] = Field(
        description="Chronological process execution chain from grandparent root to leaf process."
    )
    ancestor_chain: str = Field(
        description="Concatenated string representation (e.g., services.exe -> CcmExec.exe -> powershell.exe)."
    )
    user_privilege_level: str = Field(
        description="Security privilege context (e.g., NT AUTHORITY\\SYSTEM, LocalAdmin, StandardUser)."
    )
    anomalous_indicators: List[str] = Field(
        description="List of observed execution anomalies or suspicious flags."
    )


class ExploitOracleOutput(BaseModel):
    """Threat taxonomy classification produced by the Exploit Oracle Agent."""
    threat_tier: Literal["L0", "L1", "L2", "L3"] = Field(
        description="L0: Benign Noise, L1: Suspicious Admin Automation, L2: Active Threat Vector, L3: Critical Exploit"
    )
    mitre_technique_id: Optional[str] = Field(
        default=None,
        description="Mapped MITRE ATT&CK technique ID (e.g., T1059.001) if applicable, else None."
    )
    is_false_positive: bool = Field(
        description="True if execution is benign operational noise suitable for rule refactoring."
    )
    justification: str = Field(
        description="Detailed technical reasoning behind threat classification."
    )
    action_route: Literal["REFINE_RULE", "ESCALATE_HUMAN", "DISCARD"] = Field(
        description="REFINE_RULE if L0/L1 FP; ESCALATE_HUMAN if L2/L3 threat."
    )


class RefinedSigmaOutput(BaseModel):
    """Updated Sigma YAML rule synthesized by the Rule Refiner Agent."""
    rule_id: str = Field(description="Target Sigma Rule ID being updated.")
    title: str = Field(description="Sigma rule title.")
    sigma_yaml: str = Field(description="Complete, syntactically valid Sigma YAML string with structural exclusions.")
    added_exclusions: List[str] = Field(description="List of YAML filter keys appended to eliminate noise.")
    refinement_rationale: str = Field(description="Technical explanation of structural exclusions added.")


# ============================================================================
# 3. Regression Error Feedback Schema
# ============================================================================

class RegressionFeedbackTrace(BaseModel):
    """Feedback payload generated by Double-Loop Regression Engine on test failure."""
    iteration: int = Field(description="Current retry attempt number (1 to 3)")
    loop_failed: Literal[1, 2] = Field(
        description="1: False Positive Abatement Loop; 2: True Positive Recall Retention Loop."
    )
    error_message: str = Field(description="Detailed error trace or pySigma parsing exception")
    misfired_logs: Optional[List[Dict[str, Any]]] = Field(
        default=None,
        description="Sample historical logs that fired unexpectedly in Loop 1"
    )
    missed_attacks: Optional[List[str]] = Field(
        default=None,
        description="Atomic Red Team attack payload IDs missed in Loop 2"
    )


# ============================================================================
# 4. LangGraph State Machine Schema
# ============================================================================

class GraphADAPTState(TypedDict):
    """Global state container passed across nodes in the LangGraph workflow graph."""
    rule_id: str
    raw_subgraph: Optional[SubGraphPayload]
    correlator_output: Optional[ContextCorrelatorOutput]
    analysis_report: Optional[ExploitOracleOutput]
    current_sigma_yaml: str
    refined_rule: Optional[RefinedSigmaOutput]
    test_results: Optional[Dict[str, Any]]
    iteration: int
    error_feedback: Optional[str]
    status: str  # "PROCESSING", "RETRYING", "PASSED", "FAILED_HUMAN_REVIEW"